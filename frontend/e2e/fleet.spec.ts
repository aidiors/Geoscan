import { expect, test } from "@playwright/test";

test("creates a physical fleet, retains individual state and submits it to the real planner", async ({ page }, testInfo) => {
  await page.goto("/");
  await page.getByLabel("Модель новых бортов").selectOption("201");
  await page.getByLabel("Количество новых бортов").fill("2");
  await page.getByRole("button", { name: "＋ Добавить", exact: true }).click();
  await expect(page.locator(".fleet-row")).toHaveCount(5);
  await page.getByLabel("Название", { exact: true }).fill("201 — борт финала");
  await page.getByLabel("Текущий заряд, %", { exact: true }).fill("83");
  await page.getByLabel("Готовых комплектов АКБ", { exact: true }).fill("2");
  await page.getByLabel("Мин. обслуживание между вылетами, мин", { exact: true }).fill("5");
  await page.getByRole("button", { name: "Копировать настройки" }).click();
  await expect(page.locator(".fleet-row")).toHaveCount(6);
  await expect(page.getByLabel("Текущий заряд, %", { exact: true })).toHaveValue("83");
  await expect(page.getByLabel("Готовых комплектов АКБ", { exact: true })).toHaveValue("2");
  await page.getByRole("button", { name: "Сохранить", exact: true }).click();
  await page.getByLabel("Текущий заряд, %", { exact: true }).fill("50");
  await page.getByRole("button", { name: "Восстановить", exact: true }).click();
  await expect(page.getByLabel("Текущий заряд, %", { exact: true })).toHaveValue("83");
  await page.screenshot({ path: testInfo.outputPath("physical-fleet.png"), fullPage: true });
  const pending = page.waitForResponse((response) => response.url().endsWith("/v1/plans") && response.request().method() === "POST");
  await page.getByRole("button", { name: "Рассчитать план", exact: true }).click();
  const response = await pending;
  const request = response.request().postDataJSON();
  expect(request.drones).toHaveLength(6);
  expect(new Set(request.drones.map((drone: { drone_id: string }) => drone.drone_id)).size).toBe(6);
  const copied = request.drones.find((drone: { name: string }) => drone.name.endsWith("копия"));
  expect(copied.initial_charge_percent).toBe(83);
  expect(copied.available_battery_sets).toBe(2);
  expect(copied.minimum_turnaround_minutes).toBe(5);
  expect(response.status()).toBe(200);
  await expect(page.getByRole("button", { name: "Рассчитать план", exact: true })).toBeEnabled({ timeout: 120_000 });
  await expect(page.getByText("Все применимые проверки пройдены")).toBeVisible();
  await expect(page.getByText("Комплекты АКБ и ресурс до ТО", { exact: true })).toBeVisible();
  const card = page.locator(".mission-card").filter({ hasText: copied.name });
  const count = await card.locator("em").innerText();
  if (count !== "Не используется") expect(parseInt(count)).toBeLessThanOrEqual(2);
  await expect(page.getByRole("heading", { name: "Расчётный план" })).toBeVisible();
});
