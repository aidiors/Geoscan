import { expect, test } from "@playwright/test";
import { readFile } from "node:fs/promises";
import { randomUUID } from "node:crypto";

test("preserves project revisions, source files and reports across reload and transfer", async ({ page }, testInfo) => {
  await page.goto("/");
  const name = `Project ${randomUUID()}`;
  const field = JSON.stringify({ type: "FeatureCollection", features: [{ type: "Feature", properties: { name: "Saved field" },
    geometry: { type: "Polygon", coordinates: [[[37.394, 55.692], [37.406, 55.692], [37.406, 55.696], [37.394, 55.696], [37.394, 55.692]]] },
  }] });
  await page.locator('input[accept=".geojson,.json,.kml"]').setInputFiles({ name: "original.geojson", mimeType: "application/geo+json", buffer: Buffer.from(field) });
  await page.getByRole("button", { name: "Импортировать зону" }).click();
  await expect(page.getByText("Используется собственная геометрия задания", { exact: false })).toBeVisible();
  await page.getByRole("checkbox", { name: /Быстрый расчёт/ }).check();
  await page.getByRole("button", { name: "Рассчитать план", exact: true }).click();
  await expect(page.getByRole("button", { name: "Рассчитать план", exact: true })).toBeEnabled();
  await expect(page.getByText("Все применимые проверки пройдены")).toBeVisible();
  const inspected = page.waitForResponse((r) => r.url().endsWith("/v1/survey-quality"));
  await page.getByRole("button", { name: "Проверить отпечатки кадров", exact: true }).click();
  const quality = await (await inspected).json();
  await expect(page.getByRole("button", { name: "Проверить отпечатки кадров", exact: true })).toBeEnabled();
  await page.getByText("Проекты и история", { exact: true }).click();
  await page.getByLabel("Название проекта", { exact: true }).fill(name);
  const saved = page.waitForResponse((r) => r.url().endsWith("/v1/projects") && r.request().method() === "POST");
  await page.getByRole("button", { name: "Сохранить новый проект", exact: true }).click();
  const firstResponse = await saved;
  expect(firstResponse.status()).toBe(200);
  const first = await firstResponse.json();
  expect(first.document.source_files[0].content).toBe(field);
  expect(first.document.survey_quality.frame_count).toBe(quality.frame_count);
  expect(first.document.plan.export_authorization).toBeNull();
  expect(first.document.plan.engine_version).toBeTruthy();
  await expect(page.getByRole("button", { name: "Скачать проект", exact: true })).toBeEnabled();
  const downloaded = page.waitForEvent("download");
  await page.getByRole("button", { name: "Скачать проект", exact: true }).click();
  const path = testInfo.outputPath("geoplan-project.json");
  await (await downloaded).saveAs(path);
  const portable = JSON.parse(await readFile(path, "utf-8"));
  expect(portable.format).toBe("geoplan-project");
  await page.getByLabel("Высота задания MSL, м", { exact: true }).fill("160");
  await expect(page.getByRole("button", { name: "Сохранить ревизию", exact: true })).toBeEnabled();
  const resaved = page.waitForResponse((r) => r.url().endsWith(`/v1/projects/${first.project_id}/revisions`) && r.request().method() === "POST");
  await page.getByRole("button", { name: "Сохранить ревизию", exact: true }).click();
  const second = await (await resaved).json();
  expect(second.revision).toBe(2);
  expect(second.document.editor_state.settings.altitude).toBe(160);
  expect(second.document.plan).toBeNull();
  await page.reload();
  await page.getByText("Проекты и история", { exact: true }).click();
  await expect(page.getByLabel("Сохранённые проекты", { exact: true })).toContainText(name);
  await page.getByLabel("Сохранённые проекты", { exact: true }).selectOption(first.project_id);
  await expect(page.getByLabel("Ревизия проекта", { exact: true })).toContainText("1 ·");
  await page.getByLabel("Ревизия проекта", { exact: true }).selectOption("1");
  await page.getByRole("button", { name: "Открыть ревизию", exact: true }).click();
  await expect(page.getByText(/Архивный результат:/)).toBeVisible();
  await expect(page.getByLabel("Высота задания MSL, м", { exact: true })).toHaveValue(String(first.document.editor_state.settings.altitude));
  await expect(page.getByRole("button", { name: "GeoJSON", exact: true })).toBeEnabled();
  await expect(page.getByRole("button", { name: "QGroundControl", exact: true })).toBeDisabled();
  await expect(page.getByText("Используется собственная геометрия задания", { exact: false })).toBeVisible();
  await page.screenshot({ path: testInfo.outputPath("restored-project.png") });
  const conflicted = page.waitForResponse((r) => r.url().endsWith(`/v1/projects/${first.project_id}/revisions`) && r.request().method() === "POST");
  await page.getByRole("button", { name: "Сохранить ревизию", exact: true }).click();
  expect((await conflicted).status()).toBe(409);
  await expect(page.getByRole("status")).toContainText("другом окне");
  await expect(page.getByText(/Архивный результат:/)).toBeVisible();
  const corrupt = structuredClone(portable);
  corrupt.document.editor_state.settings.altitude += 1;
  await page.getByLabel("Импорт проекта", { exact: true }).setInputFiles({ name: "corrupt.json", mimeType: "application/json", buffer: Buffer.from(JSON.stringify(corrupt)) });
  await expect(page.getByRole("status")).toContainText("Контрольная сумма");
  await expect(page.getByText(/Архивный результат:/)).toBeVisible();
  const transferred = page.waitForResponse((r) => r.url().endsWith("/v1/projects/import"));
  await page.getByLabel("Импорт проекта", { exact: true }).setInputFiles(path);
  const imported = await (await transferred).json();
  expect(imported.project_id).not.toBe(first.project_id);
  expect(imported.document.source_files[0].content).toBe(field);
  expect(imported.document.plan.export_authorization).toBeNull();
  await expect(page.getByRole("button", { name: "Рассчитать план", exact: true })).toBeEnabled();
  await page.getByRole("button", { name: "Рассчитать план", exact: true }).click();
  await expect(page.getByRole("button", { name: "Рассчитать план", exact: true })).toBeEnabled();
  await expect(page.getByText(/Архивный результат:/)).toHaveCount(0);
  await expect(page.getByRole("button", { name: "QGroundControl", exact: true })).toBeEnabled();
});
