import { expect, test } from "@playwright/test";

test("draws a concave area, preserves layer flags and assigns a subset of ten aircraft", async ({ page }, testInfo) => {
  page.setDefaultTimeout(15_000);
  await page.goto("/");
  await expect(page.getByRole("button", { name: "Просмотр", exact: true })).toHaveAttribute("aria-pressed", "true");
  await expect(page.getByRole("button", { name: "Нарисовать область" })).toHaveCount(0);
  await page.getByRole("button", { name: "Спутник", exact: true }).click();
  await expect(page.getByLabel("Компас: север сверху")).toBeVisible();
  await page.getByRole("button", { name: "Редактирование", exact: true }).click();
  await page.getByRole("button", { name: "Нарисовать область" }).click();
  await page.getByLabel("Название контура").fill("Контур финала");
  const map = page.getByRole("img", { name: "Интерактивная карта зоны обследования" });
  const bounds = (await map.boundingBox())!;
  for (const [x, y] of [[.15, .25], [.55, .25], [.35, .4], [.55, .6], [.15, .6]]) {
    await map.click({ position: { x: bounds.width * x, y: bounds.height * y } });
  }
  await page.getByRole("button", { name: "Замкнуть контур" }).click();
  await page.getByRole("button", { name: /Управлять объектами/ }).click();
  await page.getByLabel("Найти объект", { exact: true }).fill("Контур финала");
  await page.locator(".geo-object-row").first().click();
  const layer = page.locator(".zone-item").filter({ hasText: "Контур финала" });
  await expect(layer).toBeVisible();
  await page.getByRole("button", { name: "Защитить Контур финала", exact: true }).click();
  await expect(page.getByRole("button", { name: "Удалить Контур финала", exact: true })).toBeDisabled();
  await page.getByRole("button", { name: "Скрыть Контур финала", exact: true }).click();
  await page.getByRole("button", { name: "Закрыть зоны и площадки" }).click();
  await expect(map.locator(".zone-layer title").filter({ hasText: "Контур финала" })).toHaveCount(0);
  await page.getByRole("button", { name: /Управлять парком/ }).click();
  await page.getByLabel("Количество новых бортов", { exact: true }).fill("7");
  await page.getByRole("button", { name: "＋ Добавить", exact: true }).click();
  await expect(page.locator(".fleet-row")).toHaveCount(10);
  await page.getByRole("button", { name: "Готово", exact: true }).click();
  await page.getByRole("button", { name: /Управлять объектами/ }).click();
  await page.getByLabel("Найти объект", { exact: true }).fill("");
  await page.getByLabel("Тип объектов", { exact: true }).selectOption("site");
  await page.locator('.geo-object-row[data-kind="site"]').first().click();
  const site = page.locator(".site-item").first();
  await site.locator("summary").click();
  await site.getByRole("checkbox", { name: "Весь парк", exact: true }).uncheck();
  await site.locator('fieldset input[type="checkbox"]').nth(2).check();
  await expect(site.locator("summary")).toHaveText("Назначено БВС: 2");
  await page.getByRole("button", { name: "Закрыть зоны и площадки" }).click();
  await page.getByRole("button", { name: "Сохранить черновик", exact: true }).click();
  const saved = await page.evaluate(() => JSON.parse(localStorage.getItem("geoplan-scenario")!));
  const drawn = saved.importedZones.find((zone: { name: string }) => zone.name === "Контур финала");
  expect(drawn.coordinates).toHaveLength(6);
  expect(drawn.visible).toBe(false);
  expect(drawn.locked).toBe(true);
  expect(drawn.enabled).toBe(true);
  expect(saved.sites[0].assignedDroneIds).toHaveLength(2);
  await page.getByRole("button", { name: "Удалить незакреплённые", exact: true }).click();
  await page.getByRole("button", { name: /Управлять объектами/ }).click();
  await page.getByLabel("Тип объектов", { exact: true }).selectOption("all");
  await page.getByLabel("Найти объект", { exact: true }).fill("Контур финала");
  await page.locator(".geo-object-row").first().click();
  await expect(layer).toBeVisible();
  await page.getByRole("button", { name: "Показать Контур финала", exact: true }).click();
  await page.getByRole("button", { name: "Закрыть зоны и площадки" }).click();
  await expect(map.locator(".zone-layer title").filter({ hasText: "Контур финала" })).toHaveCount(1);
  await page.getByRole("button", { name: "Открыть черновик", exact: true }).click();
  await page.getByRole("button", { name: /Управлять объектами/ }).click();
  await page.getByLabel("Найти объект", { exact: true }).fill("Контур финала");
  await page.locator(".geo-object-row").first().click();
  await expect(page.getByRole("button", { name: "Показать Контур финала", exact: true })).toBeVisible();
  await page.screenshot({ path: testInfo.outputPath("map-layers-satellite.png"), fullPage: true });
});

